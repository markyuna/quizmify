export function getCountryCoordinates(countryName: string | null | undefined): LatLng | null {
  if (!countryName) return null;

  const trimmed = countryName.trim();
  if (COUNTRY_COORDINATES[trimmed]) return COUNTRY_COORDINATES[trimmed];

  const alias = COUNTRY_ALIASES[trimmed];
  if (alias && COUNTRY_COORDINATES[alias]) return COUNTRY_COORDINATES[alias];

  return null;
}
